"""Stage 2a: the core simulation benchmark.

Five generative processes with closed-form spectra (the four of the main
figure and the alternative AR(5)) are estimated with all six timescale
estimators at a long recording duration, so that everything seen here
is model mismatch rather than finite-sample noise.  A population (Yule-Walker
on the true ACF) analysis quantifies how much AR structure each process needs
in the limit of infinite data.

Outputs
-------
results/benchmark_main.csv.gz, results/benchmark_main_summary.csv
results/population_ar.csv
"""

import os
import sys
from pathlib import Path

# One BLAS thread per worker: the Monte Carlo is parallelised over
# repetitions, and nested threading oversubscribes the machine badly.
for _var in ('OMP_NUM_THREADS', 'OPENBLAS_NUM_THREADS', 'MKL_NUM_THREADS',
             'NUMEXPR_NUM_THREADS', 'VECLIB_MAXIMUM_THREADS'):
    os.environ.setdefault(_var, '1')

import numpy as np
import pandas as pd

from tsmodes.benchmark import run_condition, summarize
from tsmodes.estimators import population_ar, is_divergence
from tsmodes.modes import ARModes, ar_psd
from tsmodes.sims import (AR1, AR2_RHYTHM, AR2Damped, ARpModes, BENCH_TAU, PowerLaw,
                          arp_process)

ROOT = Path(__file__).resolve().parents[1]
RES = ROOT / 'results'
FS = 500.0
DURATION = 100.0
N_REPS = 200
WELCH_WIN_S = 4.0
# The finite-sample column of the main figure: the same AR(1), recorded for
# twenty timescales and analysed with the same settings as the long
# recordings, so that the duration is the only thing that changes.  The
# quarter-of-the-recording rule of run_04_finite was used here before, and on
# four seconds it is a different analysis, not a shorter one: 1 s Welch
# segments put the first frequency bin at 1 Hz, above the 0.8 Hz knee of a
# 200 ms process, so the spectral fits ran to the 20 s search bound in a
# quarter of the repetitions; and 1 s of lags from 1 s segments reaches half
# the segment, where dividing out the Hann taper amplifies the lag-domain
# noise fivefold and the ACF fell below -0.7 in half the repetitions.  Kept
# here so that the figure's every column comes from one table and one
# constructed timescale.
FINITE_DURATION = 20 * BENCH_TAU
N_JOBS = int(os.environ.get('TSMODES_N_JOBS', '12'))

# Four processes, each present to answer one question; the three
# autoregressive ones are the columns of the main figure.  A rhythm the model
# cannot represent at any order -- a sinusoid added to the signal -- is the
# sweep of run_03_oscillations and the supplementary grid.
#
#   AR(1)            the positive control: the model is correct, so any
#                    estimator that fails here fails for its own reasons.
#                    Its tau is BENCH_TAU, the constructed timescale of every
#                    column of the figure.
#   AR(2) oscillator a rhythm the model represents exactly, generated by the
#                    dynamics.  The same rhythm as the oscillations column of
#                    fig_bias.
#   AR(p)            inside the model family but above first order.  Separates
#                    model mismatch from mere order mismatch, which every
#                    other failing process confounds.  Same AR(7) as the
#                    modes figure, so the two describe one process.  The
#                    alternative AR(5) (tsmodes.sims.ARP_MODES_5) is simulated
#                    alongside so the figures can draw either; it is not in
#                    the main figure.
#   power law        outside the family and with no characteristic timescale
#                    at all, so there is nothing for an estimator to recover.
PROCESSES = [
    AR1(tau=BENCH_TAU),
    AR2Damped(tau=AR2_RHYTHM[0], f_osc=AR2_RHYTHM[1]),
    ARpModes(),
    arp_process('5'),
    PowerLaw(d=0.45),
]
SHORT_LABELS = ['AR(1)', 'AR(2) oscillator', ARpModes().label, arp_process('5').label, 'Power law']
MAIN_PROCESSES = ['ar1', 'ar2_damped', 'arp_modes', 'power_law']
MAX_ORDER = 30
YLIM = (-3.1, 1.7)     # log10 seconds, for panel c; wide enough that
                       # every box fits and no off-scale marker is needed

# Processes whose ground-truth timescale is the decay of an *intrinsic*
# oscillator: there the AR(p) answer is the oscillatory mode, not a relaxation
# mode.  AR(1)-family estimators can only ever report a single relaxation time.
OSCILLATORY_TRUTH = {'ar2_damped'}


def add_target_column(df):
    """The timescale each estimator is being asked for, per process."""
    target = np.where(
        df['method'].str.startswith('ar1_'), df['tau'],
        np.where(df['process'].isin(OSCILLATORY_TRUTH),
                 df.get('top_osc_tau', np.nan), df['tau_relaxation']))
    out = df.copy()
    out['tau_target'] = target.astype(float)
    return out


def enbw(fs, nperseg):
    w = np.hanning(nperseg)
    return fs * np.sum(w ** 2) / np.sum(w) ** 2


def population_analysis(processes, fs, orders=range(1, MAX_ORDER + 1),
                        max_lag_s=8.0, welch_win_s=WELCH_WIN_S):
    """How well can an AR(p) represent each process given infinite data?"""
    nperseg = int(welch_win_s * fs)
    freqs = np.fft.rfftfreq(nperseg, 1 / fs)
    band = (freqs >= 1.0) & (freqs <= fs / 2)
    bw = enbw(fs, nperseg)
    nlags = int(max_lag_s * fs)

    rows = []
    for proc in processes:
        rho = proc.acf(np.arange(nlags + 1), fs)
        target = proc.psd_with_lines(freqs, fs, bw)[band]
        for p in orders:
            phi = population_ar(rho, p)
            model = ar_psd(phi, freqs[band], fs, 1.0)
            model = model * np.mean(target / model)  # IS-optimal scale
            modes = ARModes.from_phi(phi, fs, freqs=freqs[band])
            dom = modes.dominant_subset(tol=0.1)
            rows.append({
                'process': proc.name, 'label': proc.label, 'order': p,
                'is_div': is_divergence(target, model),
                'rmse_logpsd': float(np.sqrt(np.mean(
                    (np.log10(target) - np.log10(model)) ** 2))),
                'n_modes': len(modes.modes),
                'n_dominant_modes': dom['n_modes'],
                'tau_dominant': modes.tau_dominant,
                'tau_relaxation': modes.tau_relaxation,
                'top_osc_freq': next((m.freq for m in modes.modes
                                      if m.kind == 'oscillatory'), np.nan),
                'tau_integrated': proc.tau_integrated(fs),
                'tau_true': proc.tau_true,
                'is_stationary': modes.is_stationary,
            })
    return pd.DataFrame(rows)


def main():
    RES.mkdir(exist_ok=True)

    print('Population AR analysis ...', flush=True)
    pop = population_analysis(PROCESSES, FS)
    pop.to_csv(RES / 'population_ar.csv', index=False)

    cache = RES / 'benchmark_main.csv.gz'
    if cache.exists() and '--rerun' not in sys.argv:
        print(f'Loading cached {cache.name} (pass --rerun to recompute)',
              flush=True)
        df = pd.read_csv(cache)
    else:
        print(f'Monte Carlo: {len(PROCESSES)} processes x {N_REPS} reps',
              flush=True)
        rows = []
        for proc in PROCESSES:
            print(f'  {proc.name}', flush=True)
            rows.extend(run_condition(proc, fs=FS, duration=DURATION,
                                      n_reps=N_REPS, seed=11, n_jobs=N_JOBS,
                                      prep_kwargs={'welch_win_s': WELCH_WIN_S}))
        print(f'  ar1, {FINITE_DURATION:g} s (finite sample)', flush=True)
        rows.extend(run_condition(AR1(tau=BENCH_TAU), fs=FS, duration=FINITE_DURATION,
                                  n_reps=N_REPS, seed=13, n_jobs=N_JOBS,
                                  prep_kwargs={'welch_win_s': WELCH_WIN_S}))
        df = pd.DataFrame(rows)
        df.to_csv(cache, index=False, compression='gzip')
    df = add_target_column(df)

    summary = summarize(df, truth_col='tau_true', value_col='tau_target')
    summary.to_csv(RES / 'benchmark_main_summary.csv', index=False)
    summary_int = summarize(df, truth_col='tau_integrated',
                            value_col='tau_target')
    summary_int.to_csv(RES / 'benchmark_main_summary_integrated.csv', index=False)
    cols = ['process', 'method', 'truth', 'median', 'rel_bias', 'rel_error',
            'rel_sd', 'r2_logpsd_median', 'order_median']
    print('\n--- vs the constructed tau ---')
    print(summary[cols].to_string(index=False))
    print('\n--- vs the integrated timescale ---')
    print(summary_int[cols].to_string(index=False))



if __name__ == '__main__':
    main()
